#!/usr/bin/env python3
"""Write a second, isolated copy of the compose stack so it can run beside the main one.

The main stack owns the compose project `teammates`, the networks `teammates-*`, the subnet
172.30.28.0/24, the TEAMS-ISO chain, /run/teammates and ports 18080/18081/18443. This script derives a
file with a new project name, networks, subnet, chain, socket dir and ports, plus an optional second API
instance that shares the same Postgres (for multi-instance tests). docker-compose.yml is not modified.

  python3 scripts/gen-stack-compose.py archgaps --subnet 172.30.38 --http 28080 --api 28081 --out .stack-archgaps.yml
  STACK=archgaps STACK_SUBNET=172.30.38 ISOLATION_CHAIN=ARCHGAPS-ISO \
    docker compose -f .stack-archgaps.yml up -d --build
"""
from __future__ import annotations

import argparse
import copy
import pathlib
import re

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("name")
    ap.add_argument("--subnet", required=True, help="first three octets, e.g. 172.30.38")
    ap.add_argument("--http", type=int, required=True)
    ap.add_argument("--https", type=int)
    ap.add_argument("--api", type=int, required=True)
    ap.add_argument("--api2", type=int, help="publish a second API instance on this port")
    ap.add_argument("--chain", help="iptables chain, default <NAME>-ISO upper-case")
    ap.add_argument("--out", required=True)
    ap.add_argument("--no-cpu-limits", action="store_true",
                    help="drop cpus: quotas (test stacks; small CFS quotas get stuck throttled on this host, see docs/ARCH_G3_STATUS.md)")
    a = ap.parse_args()
    name, chain = a.name, a.chain or (a.name.upper() + "-ISO")
    text = (ROOT / "docker-compose.yml").read_text()
    text = text.replace("172.30.28", a.subnet).replace("/run/teammates", f"/run/{name}")
    text = text.replace("teammates-computer:dev", f"{name}-computer:dev")
    text = re.sub(r"name: teammates-(back|computers|dockerctl)", lambda m: f"name: {name}-{m.group(1)}", text)
    text = text.replace("COMPUTE_NETWORK: teammates-computers", f"COMPUTE_NETWORK: {name}-computers")
    text = re.sub(r"^name: teammates$", f"name: {name}", text, flags=re.M)
    doc = yaml.safe_load(text)
    doc["services"]["caddy"]["ports"] = [f"127.0.0.1:{a.http}:80"] + ([f"127.0.0.1:{a.https}:443"] if a.https else [])
    doc["services"]["api"]["ports"] = [f"127.0.0.1:{a.api}:8080"]
    doc["services"]["api"]["environment"]["COMPUTE_STACK"] = name
    iso = doc["services"]["isolation"]["environment"]
    iso["ISOLATION_SUBNET"] = a.subnet
    iso["ISOLATION_CHAIN"] = chain
    for svc in ("api", "agent", "web", "caddy"):
        doc["services"][svc].pop("container_name", None)
    # Dev stacks do not need to survive a reboot.
    for svc in doc["services"].values():
        if svc.get("restart") == "unless-stopped":
            svc["restart"] = "no"
    if a.no_cpu_limits:
        for svc in doc["services"].values():
            svc.pop("cpus", None)
    if a.api2:
        api2 = copy.deepcopy(doc["services"]["api"])
        api2["ports"] = [f"127.0.0.1:{a.api2}:8080"]
        api2["networks"] = {"front": {}, "back": {}, "dockerctl": {}}
        doc["services"]["api2"] = api2
        doc["services"]["agent"]["depends_on"]["api"] = {"condition": "service_healthy"}
    # Build contexts and mounts in the generated file are relative to its own directory.
    out = pathlib.Path(a.out)
    out.write_text("# Generated by scripts/gen-stack-compose.py; do not commit.\n" + yaml.safe_dump(doc, sort_keys=False))
    print(f"wrote {out} (project {name}, subnet {a.subnet}.0/24, chain {chain}, http {a.http}, api {a.api})")


if __name__ == "__main__":
    main()
